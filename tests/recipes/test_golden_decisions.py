"""The floor's decisions on the fixture are pinned, so a change that moves one is a decision.

The golden files hold what the floor DECIDED for the fixture recording (the channel table, the bad
segments, the plan hash, the rules, the skipped steps and the applied filters), not a measurement
that depends on how a sum is accumulated. They are generated by `scripts/make_floor_golden.py`.

Three rules sit on them (docs/recipes.md):

* any change under `recipes/nemar_process/common/` that alters a byte of these files is a
  `nemar-floor` version bump; one that does not bumps only `COMMON_VERSION`; before the first
  release a bump is the next iteration `-b<N+1>`, at most once between two image publications,
  and from the first release it is a patch (docs/recipes.md);
* a version bump regenerates them into the directory of the new version (the directory is
  `nemar-floor-` and `RECIPE_VERSION`), and a bump that changes no decision changes only
  `recipe.version` and `plan_hash` in `decisions.json`: the plan hash covers the recipe's name and
  version, so it moves with the version, and the channel and bad-segment tables stay byte-identical
  (the move from 1.0.0 to 1.0.0-b1 is such a bump:
  `test_the_fixture_plan_moved_only_by_its_version`);
* they were generated on macOS (arm64) and reproduced by CI on a hosted Linux runner (x86-64). A
  difference on another host is a finding to record (O6), not a reason to loosen this test.
"""

from __future__ import annotations

import json

import make_floor_golden as golden
import pytest
from nemar_process.common import plan
from nemar_process.nemar_floor.steps import RECIPE_VERSION
from recipe_support import PINNED_RECIPE_VERSION, ROOT

# The plan hash of the fixture at nemar-floor 1.0.0, written out: the steps, their parameters and the
# skips are what 1.0.0 had, so the hash at 1.0.0-b1 differs from it by the version alone.
HASH_AT_1_0_0 = "sha256:ffa6a154580dd7099bb4f2a6a5bf7a9b3f1f2ffc6a99e9a2603124702ebe35fd"

MESSAGE = (
    "{} differs from the pinned decision. If a recipe or the common layer changed on purpose, that "
    "is a nemar-floor version bump and the golden files are regenerated with "
    "scripts/make_floor_golden.py. If nothing changed and this is a new host, record the "
    "difference as a finding (docs/recipes.md, O6)."
)


def test_a_fresh_run_makes_the_pinned_decisions(floor_product):
    directory, product = floor_product
    fresh = golden.golden_files(directory, product.record)
    assert set(fresh) == {"channels.tsv", "badsegments.tsv", "decisions.json"}
    for name, text in fresh.items():
        pinned = (golden.GOLDEN / name).read_text(encoding="utf-8")
        assert text == pinned, MESSAGE.format(name)


def test_the_decisions_are_the_ones_the_phase_plan_observed_on_the_fixture():
    pinned = json.loads((golden.GOLDEN / "decisions.json").read_text(encoding="utf-8"))
    assert pinned["bad_channels_removed"] == ["O1", "T6"]
    assert pinned["bad_channels_branch"] == "ransac"
    assert pinned["noise_only_channels"] == ["Pg1", "Pg2"]  # no coordinates, judged on noise alone
    assert pinned["not_assessed_channels"] == []
    assert pinned["n_bad_segments"] == 40
    assert pinned["flatline_removed"] == []
    assert pinned["line_noise_removed_hz"] == []
    assert pinned["drift_kernel_length"] == 1005
    segments = (golden.GOLDEN / "badsegments.tsv").read_text(encoding="utf-8").splitlines()
    assert len(segments) == 1 + 40
    channels = (golden.GOLDEN / "channels.tsv").read_text(encoding="utf-8").splitlines()
    assert [line.split("\t")[0] for line in channels[1:]][-1] == "ECG"
    assert sum(1 for line in channels if "\tbad\t" in line) == 2


def test_the_script_makes_what_the_fixture_run_makes(floor_product):
    """`produce` is what the script writes the golden files from; it is the one extra run here."""
    directory, product = floor_product
    assert golden.produce() == golden.golden_files(directory, product.record)


def test_the_script_agrees_with_the_committed_files(floor_product):
    directory, product = floor_product
    assert golden.main(["--check"], produced=golden.golden_files(directory, product.record)) == 0


def test_the_script_notices_a_changed_golden_file(floor_product, tmp_path, monkeypatch, capsys):
    import shutil

    directory, product = floor_product
    copy = tmp_path / "golden"
    shutil.copytree(golden.GOLDEN, copy)
    (copy / "channels.tsv").write_text("name\ttype\n", encoding="utf-8")
    monkeypatch.setattr(golden, "GOLDEN", copy)
    fresh = golden.golden_files(directory, product.record)
    assert golden.main(["--check"], produced=fresh) == 1
    assert "channels.tsv differs" in capsys.readouterr().err


@pytest.mark.parametrize("name", ["channels.tsv", "badsegments.tsv", "decisions.json"])
def test_a_golden_file_that_is_missing_fails_the_check_and_is_never_written_by_it(
    floor_product, tmp_path, monkeypatch, capsys, name
):
    """The comparison is strict in both directions: no file to compare with is a difference."""
    import shutil

    directory, product = floor_product
    copy = tmp_path / "golden"
    shutil.copytree(golden.GOLDEN, copy)
    (copy / name).unlink()
    monkeypatch.setattr(golden, "GOLDEN", copy)
    fresh = golden.golden_files(directory, product.record)
    assert golden.main(["--check"], produced=fresh) == 1
    assert "{} differs".format(name) in capsys.readouterr().err
    assert not (copy / name).exists()


@pytest.mark.parametrize("name", ["channels.tsv", "badsegments.tsv", "decisions.json"])
def test_every_golden_file_is_committed_text_with_a_final_newline(name):
    text = (golden.GOLDEN / name).read_text(encoding="utf-8")
    assert text.endswith("\n")
    assert "\r" not in text


def test_the_fixture_plan_moved_only_by_its_version(floor_product):
    """Re-hashed with the version set back to 1.0.0, the fixture's resolved plan is 1.0.0's hash:
    no step, parameter, rule or skip changed, so the plan moved by its version and nothing else."""
    _, product = floor_product
    resolved = plan.resolved_plan(product.record)
    assert resolved["recipe_version"] == PINNED_RECIPE_VERSION
    assert plan.plan_hash({**resolved, "recipe_version": "1.0.0"}) == HASH_AT_1_0_0
    # and the version is in the hash: at the current version the hash is the pinned one, and it is
    # 1.0.0's hash exactly when the version is 1.0.0, so the first release changes no test logic
    assert plan.plan_hash(resolved) == product.record["extensions"]["nemar"]["plan_hash"]
    assert (plan.plan_hash(resolved) == HASH_AT_1_0_0) == (RECIPE_VERSION == "1.0.0")
    pinned = json.loads((golden.GOLDEN / "decisions.json").read_text(encoding="utf-8"))
    assert pinned["plan_hash"] == plan.plan_hash(resolved)
    assert pinned["recipe"] == {"id": "nemar-floor", "version": PINNED_RECIPE_VERSION}


def test_the_hash_at_1_0_0_is_written_once_in_the_rule_and_in_the_script():
    # docs/recipes.md and the script's docstring write out the hash the first release returns to;
    # HASH_AT_1_0_0 is the copy the re-hash above proves, so a copy that drifts fails here
    rule = (ROOT / "docs" / "recipes.md").read_text(encoding="utf-8")
    assert rule.count(HASH_AT_1_0_0) == 1
    script = golden.__doc__ or ""
    assert script.count(HASH_AT_1_0_0) == 1


def test_the_golden_directory_is_named_for_the_recipe_version():
    assert golden.GOLDEN.name == "nemar-floor-" + RECIPE_VERSION
    assert golden.GOLDEN.is_dir()
